"""One-shot schema migration: what the `migrate` compose service runs.

Every long-running Python service `depends_on` this with
`condition: service_completed_successfully`, so the schema is brought up to
date exactly once, by one process, before any worker starts.

How the schema is applied, in order of preference:

1. Alembic - when the `alembic` package is installed AND at least one revision
   exists under trader/engine/alembic/versions/: `alembic upgrade head`.
   A database that predates Alembic (application tables exist, no revision
   stamped in `alembic_version`) is first stamped at the base revision, because
   that base revision is - by construction, see trader/engine/alembic/README.md -
   the autogenerated snapshot of exactly that schema.
   Set MIGRATE_AUTO_STAMP=false to refuse instead and stamp by hand.

2. Otherwise `Base.metadata.create_all` (checkfirst): the same bootstrap the
   workers still run in `init_db`, just done once instead of four times at the
   same moment. create_all only ADDS missing tables; it never alters an
   existing one - which is why path 1 exists. Until then, the few columns
   added to existing tables are listed in `db.session.ADDITIVE_COLUMNS` and
   applied here (and in `init_db`) with an idempotent ALTER TABLE; the
   equivalent hand SQL is next to that list.

Exit code 0 = schema ready; anything else = the workers must not start.

    python -m app.db.migrate            # what the compose service runs
    python -m app.db.migrate --check    # print which path would be taken, touch nothing
"""
from __future__ import annotations

import asyncio
import importlib.util
import logging
import os
import sys
from pathlib import Path

from sqlalchemy import inspect, text

from app.db.models import Base
from app.db.session import add_missing_columns, dispose_db, get_engine
from app.util.logging_setup import setup_logging

log = setup_logging("migrate")

# /srv in the image, trader/engine in the repository.
ENGINE_ROOT = Path(__file__).resolve().parents[2]
ALEMBIC_INI = ENGINE_ROOT / "alembic.ini"
VERSIONS_DIR = ENGINE_ROOT / "alembic" / "versions"


def revision_files() -> list[Path]:
    if not VERSIONS_DIR.is_dir():
        return []
    return sorted(p for p in VERSIONS_DIR.glob("*.py") if not p.name.startswith("_"))


def alembic_installed() -> bool:
    # Look for a real submodule: the migrations directory /srv/alembic (no
    # __init__.py) is importable as an empty *namespace* package, so a bare
    # find_spec("alembic") is true even when the library is not installed.
    try:
        return importlib.util.find_spec("alembic.config") is not None
    except (ImportError, ValueError):
        return False


def _truthy(value: str | None, default: bool) -> bool:
    if value is None or value.strip() == "":
        return default
    return value.strip().lower() not in ("0", "false", "no", "off")


async def wait_for_db(retries: int = 90, delay: float = 2.0) -> None:
    """Block until Postgres accepts connections (covers a slow recovery after a hard reboot)."""
    engine = get_engine()
    last_error: Exception | None = None
    for attempt in range(1, retries + 1):
        try:
            async with engine.connect() as conn:
                await conn.execute(text("SELECT 1"))
            log.info("database reachable")
            return
        except Exception as exc:  # noqa: BLE001 - retry any connection failure
            last_error = exc
            log.warning("database not ready (attempt %s/%s): %s", attempt, retries, exc)
            await asyncio.sleep(delay)
    raise RuntimeError(f"could not reach the database: {last_error}")


async def db_state() -> tuple[bool, bool]:
    """Return (application tables exist, a revision is stamped in alembic_version).

    The *row* matters, not the table: `alembic revision --autogenerate` creates
    an empty alembic_version table as a side effect, which must not be mistaken
    for a stamped database.
    """
    engine = get_engine()
    async with engine.connect() as conn:
        names = await conn.run_sync(lambda sync_conn: set(inspect(sync_conn).get_table_names()))
        stamped = False
        if "alembic_version" in names:
            result = await conn.execute(text("SELECT count(*) FROM alembic_version"))
            stamped = bool(result.scalar())
    app_tables = {table.name for table in Base.metadata.sorted_tables}
    return bool(app_tables & names), stamped


async def create_all() -> None:
    engine = get_engine()
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
        added = await conn.run_sync(add_missing_columns)
    if added:
        log.info("added columns to existing tables: %s", ", ".join(added))


async def _prepare() -> tuple[bool, bool]:
    try:
        await wait_for_db()
        return await db_state()
    finally:
        # Each asyncio.run() gets a fresh engine; asyncpg connections are bound to their loop.
        await dispose_db()


async def _create_all_once() -> None:
    try:
        await create_all()
    finally:
        await dispose_db()


def run_alembic(has_tables: bool, stamped: bool) -> None:
    from alembic import command
    from alembic.config import Config
    from alembic.script import ScriptDirectory

    os.chdir(ENGINE_ROOT)
    cfg = Config(str(ALEMBIC_INI))
    if has_tables and not stamped:
        if not _truthy(os.environ.get("MIGRATE_AUTO_STAMP"), default=True):
            raise SystemExit(
                "the database predates Alembic (tables exist, no alembic_version) and "
                "MIGRATE_AUTO_STAMP is off - run `alembic stamp <baseline-revision>` by hand"
            )
        base = ScriptDirectory.from_config(cfg).get_base()
        log.warning(
            "existing schema without alembic_version - stamping base revision %s "
            "(the baseline must be the autogenerated snapshot of this schema)", base,
        )
        command.stamp(cfg, base)
    log.info("alembic upgrade head")
    command.upgrade(cfg, "head")


def main(argv: list[str]) -> int:
    check_only = "--check" in argv
    revisions = revision_files()
    use_alembic = alembic_installed() and bool(revisions)

    has_tables, stamped = asyncio.run(_prepare())
    log.info(
        "schema source: %s (alembic installed: %s, revisions: %d, tables present: %s, stamped: %s)",
        "alembic" if use_alembic else "create_all",
        alembic_installed(), len(revisions), has_tables, stamped,
    )
    if not alembic_installed():
        log.info("alembic is not installed - create_all cannot ALTER existing tables; "
                 "see trader/engine/alembic/README.md before the first model change")
    if check_only:
        return 0

    if use_alembic:
        run_alembic(has_tables, stamped)
    else:
        asyncio.run(_create_all_once())
    log.info("database schema ready")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except SystemExit:
        raise
    except Exception as exc:  # noqa: BLE001 - a non-zero exit is the whole point
        log.error("migration failed: %s", exc, exc_info=True)
        sys.exit(1)
